"""Export published episodes from the Mental Models Daily database to _data/episodes.yml.

Usage: python3 scripts/export_episodes.py path/to/mental_models.db

An episode counts as published when it has an RSS link. To add a thumbnail,
save it as img/episodes/<slug>.png; the export picks it up automatically.
"""
import json
import re
import sqlite3
import sys
from email.utils import parsedate_to_datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
YOUTUBE = "https://www.youtube.com/@MentalModelsDaily/podcasts"


def slugify(text):
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def strip_html(text):
    return re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " ", text or "")).strip()


def main(db_path):
    con = sqlite3.connect(f"file:{db_path}?mode=ro", uri=True)
    rows = con.execute(
        """SELECT e.title, m.category, m.short_caption, m.description, e.description,
                  e.rss_link, e.rss_pubdate
           FROM episodes e LEFT JOIN mental_models m ON m.id = e.mental_model_id
           WHERE e.rss_link IS NOT NULL AND e.rss_link != ''"""
    ).fetchall()

    episodes = []
    for title, category, caption, model_desc, ep_desc, link, pubdate in rows:
        date = parsedate_to_datetime(pubdate).date()
        slug = slugify(title)
        first_para = re.search(r"<p>(.*?)</p>", ep_desc or "")
        summary = caption or model_desc or strip_html(first_para.group(1) if first_para else "")
        thumb = f"/img/episodes/{slug}.png"
        episodes.append({
            "title": title.strip(),
            "category": category,
            "date": date.isoformat(),
            "summary": summary.strip(),
            "thumbnail": thumb if (ROOT / thumb.lstrip("/")).exists() else None,
            "spotify": link,
            "youtube": YOUTUBE,
            "published": True,
        })

    episodes.sort(key=lambda e: e["date"], reverse=True)
    out = ROOT / "_data" / "episodes.yml"
    with out.open("w") as f:
        f.write("# Generated by scripts/export_episodes.py - edit the database, then re-run.\n")
        for ep in episodes:
            # JSON scalars are valid YAML, which keeps quoting safe.
            f.write("- " + "\n  ".join(f"{k}: {json.dumps(v, ensure_ascii=False)}" for k, v in ep.items()) + "\n")
    print(f"Wrote {len(episodes)} episodes to {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main(sys.argv[1])
