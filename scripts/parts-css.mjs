// Writes the situation colours from src/data/parts.json to src/styles/parts.generated.css (SPEC.md §5),
// so they ship in the main stylesheet instead of as a separate request. Runs before dev and build.
import { readFileSync, writeFileSync } from "node:fs";

const parts = JSON.parse(readFileSync(new URL("../src/data/parts.json", import.meta.url), "utf8"));
const CREAM = "#FFFAE5";

const channel = (v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4);
const luminance = (hex) => {
  const [r, g, b] = [1, 3, 5].map((i) => channel(parseInt(hex.slice(i, i + 2), 16) / 255));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const contrast = (a, b) => {
  const [x, y] = [luminance(a), luminance(b)].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
};

const css = parts.map(({ code, colours: { bg, fg, accent } }) => {
  // On cream, type and drawings use the part's first colour that passes AA (BRAND.md).
  const ink = [bg, fg, accent].find((c) => contrast(c, CREAM) >= 4.5) ?? "#111111";
  return `[data-part="${code}"] { --part-bg: ${bg}; --part-fg: ${fg}; --part-accent: ${accent}; --part-ink: ${ink}; }`;
});
writeFileSync(
  new URL("../src/styles/parts.generated.css", import.meta.url),
  `/* Generated by scripts/parts-css.mjs from src/data/parts.json. Do not edit. */\n${css.join("\n")}\n`,
);
